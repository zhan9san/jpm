use std::collections::HashMap;

use crate::resolver::ResolvedPlugin;

/// Compute a stable SHA-256 hex digest of the manifest content.
/// Stored in the lock file header so we can detect when `plugins.txt` changes.
pub fn manifest_hash(content: &str) -> String {
    // Use a simple but stable FNV-64 hash encoded as hex — good enough for
    // staleness detection (not a cryptographic use case).
    let mut hasher = FnvHasher::default();
    hasher.write(content.as_bytes());
    format!("{:016x}", hasher.finish())
}

/// FNV-1a 64-bit hasher — zero-dependency, deterministic across runs.
#[derive(Default)]
struct FnvHasher(u64);

impl FnvHasher {
    fn write(&mut self, bytes: &[u8]) {
        let mut hash: u64 = 14695981039346656037;
        for &b in bytes {
            hash ^= u64::from(b);
            hash = hash.wrapping_mul(1099511628211);
        }
        self.0 = hash;
    }
    fn finish(&self) -> u64 {
        self.0
    }
}

/// Render the resolved plugin map as a `plugins-lock.txt` string.
///
/// Format:
/// ```
/// # Generated by jpm — do not edit manually
/// # Jenkins: 2.452.4
/// # manifest-hash: a3f1b2c4d5e6f7a8
/// #
/// # name:version sha256:<b64> [url:<url>]
/// git:5.7.0 sha256:abc123...
/// credentials:1415.v831096eb_5534 sha256:def456...
/// ```
///
/// Plugins are sorted alphabetically so the file diffs cleanly in git.
/// Integrity checksums are included when available from the Update Center.
pub fn render(
    plugins: &HashMap<String, ResolvedPlugin>,
    jenkins_version: &str,
    manifest_content: &str,
    include_sha256: bool,
) -> String {
    let mut out = String::with_capacity(plugins.len() * 64);

    out.push_str("# Generated by jpm — do not edit manually\n");
    out.push_str(&format!("# Jenkins: {jenkins_version}\n"));
    out.push_str(&format!(
        "# manifest-hash: {}\n",
        manifest_hash(manifest_content)
    ));
    out.push('\n');

    let mut sorted: Vec<&ResolvedPlugin> = plugins.values().collect();
    sorted.sort_by_key(|p| &p.name);

    for plugin in sorted {
        let checksum = if include_sha256 {
            plugin
                .sha256
                .as_deref()
                .map(|h| format!(" sha256:{h}"))
                .unwrap_or_default()
        } else {
            String::new()
        };
        let url = plugin
            .url
            .as_deref()
            .map(|u| format!(" url:{u}"))
            .unwrap_or_default();
        out.push_str(&format!(
            "{}:{}{checksum}{url}\n",
            plugin.name, plugin.version
        ));
    }

    out
}

/// One plugin line of a lock file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockEntry {
    pub version: String,
    /// Base64 SHA-256 of the archive (`sha256:` field).
    pub sha256: Option<String>,
    /// Source URL for plugins not taken from the Update Center (`url:` field).
    pub url: Option<String>,
}

/// Parse a `plugins-lock.txt` file back into a map of `name → LockEntry`.
/// Lines starting with `#` and blank lines are ignored.
///
/// Line format: `name:version [sha256:<b64>] [url:<url>]`.
pub fn parse(content: &str) -> HashMap<String, LockEntry> {
    content
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .filter_map(|line| {
            let mut fields = line.split_whitespace();
            let (name, version) = fields.next()?.split_once(':')?;
            let mut entry = LockEntry {
                version: version.trim().to_string(),
                sha256: None,
                url: None,
            };
            for field in fields {
                if let Some(v) = field.strip_prefix("sha256:") {
                    entry.sha256 = Some(v.to_string());
                } else if let Some(v) = field.strip_prefix("url:") {
                    entry.url = Some(v.to_string());
                }
            }
            Some((name.trim().to_string(), entry))
        })
        .collect()
}

/// Extract the `manifest-hash` header value from a lock file, if present.
pub fn parse_manifest_hash(content: &str) -> Option<String> {
    content.lines().find_map(|line| {
        line.strip_prefix("# manifest-hash: ")
            .map(|h| h.trim().to_string())
    })
}

/// Extract the `Jenkins` header value from a lock file, if present.
pub fn parse_jenkins_version(content: &str) -> Option<String> {
    content.lines().find_map(|line| {
        line.strip_prefix("# Jenkins: ")
            .map(|v| v.trim().to_string())
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn make_plugin(name: &str, version: &str, sha256: Option<&str>) -> ResolvedPlugin {
        ResolvedPlugin {
            name: name.to_string(),
            version: version.to_string(),
            sha256: sha256.map(str::to_owned),
            is_direct: true,
            url: None,
        }
    }

    #[test]
    fn render_and_parse_roundtrip() {
        let mut plugins = HashMap::new();
        plugins.insert(
            "git".to_string(),
            make_plugin("git", "5.7.0", Some("aabbccdd")),
        );
        plugins.insert(
            "credentials".to_string(),
            make_plugin("credentials", "1415.v831096eb_5534", None),
        );

        let rendered = render(&plugins, "2.452.4", "git\ncredentials\n", true);
        assert!(rendered.contains("git:5.7.0 sha256:aabbccdd"));
        assert!(rendered.contains("credentials:1415.v831096eb_5534\n"));

        let parsed = parse(&rendered);
        assert_eq!(parsed["git"].version, "5.7.0");
        assert_eq!(parsed["git"].sha256.as_deref(), Some("aabbccdd"));
        assert_eq!(parsed["credentials"].version, "1415.v831096eb_5534");
        assert!(parsed["credentials"].sha256.is_none());
    }

    #[test]
    fn render_and_parse_url_field() {
        let mut plugin = make_plugin("my-plugin", "1.0", Some("c2hh"));
        plugin.url = Some("https://repo.example/my-plugin-1.0.hpi".to_string());
        let plugins = HashMap::from([("my-plugin".to_string(), plugin)]);

        let rendered = render(&plugins, "2.452.4", "", true);
        assert!(rendered
            .contains("my-plugin:1.0 sha256:c2hh url:https://repo.example/my-plugin-1.0.hpi\n"));
        let parsed = parse(&rendered);
        assert_eq!(
            parsed["my-plugin"],
            LockEntry {
                version: "1.0".into(),
                sha256: Some("c2hh".into()),
                url: Some("https://repo.example/my-plugin-1.0.hpi".into()),
            }
        );

        let rendered = render(&plugins, "2.452.4", "", false);
        assert!(rendered.contains("my-plugin:1.0 url:https://repo.example/my-plugin-1.0.hpi\n"));
        assert!(parse(&rendered)["my-plugin"].sha256.is_none());
    }

    #[test]
    fn alphabetical_ordering() {
        let mut plugins = HashMap::new();
        for name in &["zebra", "alpha", "mango"] {
            plugins.insert(name.to_string(), make_plugin(name, "1.0", None));
        }
        let rendered = render(&plugins, "2.452.4", "", true);
        let names: Vec<&str> = rendered
            .lines()
            .filter(|l| !l.starts_with('#') && !l.is_empty())
            .collect();
        assert_eq!(names, vec!["alpha:1.0", "mango:1.0", "zebra:1.0"]);
    }

    #[test]
    fn manifest_hash_is_stable() {
        let h1 = manifest_hash("git\ncredentials\n");
        let h2 = manifest_hash("git\ncredentials\n");
        assert_eq!(h1, h2);
    }

    #[test]
    fn manifest_hash_differs_on_change() {
        let h1 = manifest_hash("git\ncredentials\n");
        let h2 = manifest_hash("git\ncredentials\ndocker\n");
        assert_ne!(h1, h2);
    }

    #[test]
    fn parse_manifest_hash_roundtrip() {
        let plugins: HashMap<String, ResolvedPlugin> = HashMap::new();
        let manifest = "git\ncredentials\n";
        let rendered = render(&plugins, "2.452.4", manifest, true);
        let extracted = parse_manifest_hash(&rendered).unwrap();
        assert_eq!(extracted, manifest_hash(manifest));
    }

    #[test]
    fn parse_jenkins_version_roundtrip() {
        let plugins: HashMap<String, ResolvedPlugin> = HashMap::new();
        let rendered = render(&plugins, "2.452.4", "git\n", true);
        let extracted = parse_jenkins_version(&rendered).unwrap();
        assert_eq!(extracted, "2.452.4");
    }

    #[test]
    fn render_without_sha256_omits_checksum_suffix() {
        let mut plugins = HashMap::new();
        plugins.insert(
            "git".to_string(),
            make_plugin("git", "5.7.0", Some("aabbccdd")),
        );
        let rendered = render(&plugins, "2.452.4", "git\n", false);
        assert!(rendered.contains("git:5.7.0\n"));
        assert!(!rendered.contains("sha256:"));
    }
}
